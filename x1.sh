clear


while true; do

    echo "╔════════════════════════════════╗"
    echo "║            X1 MENU            ║"
    echo "╠════════════════════════════════╣"
    echo "║ [1] Start                     ║"
    echo "║ [2] About                     ║"
    echo "║ [0] Exit                      ║"
    echo "╚════════════════════════════════╝"
    echo

    echo -n "Select: "
    read choice

    case "$choice" in

        # ==================================================
        # START
        # ==================================================

        1)

            while true; do

                clear

                echo "╔══════════════════════════════════════╗"
                echo "║              X1 START               ║"
                echo "╠══════════════════════════════════════╣"
                echo "║ [1] Full Site Information            ║"
                echo "║ [2] DNS Information                  ║"
                echo "║ [3] HTTP Headers                     ║"
                echo "║ [4] TLS Certificate                  ║"
                echo "║ [5] Security Headers                 ║"
                echo "║ [0] Back                             ║"
                echo "╚══════════════════════════════════════╝"
                echo

                echo -n "Select: "
                read start_choice

                case "$start_choice" in

                    # ======================================
                    # FULL SITE INFORMATION
                    # ======================================

                    1)

                        clear

                        echo "╔══════════════════════════════════════╗"
                        echo "║       X1 FULL SITE INFORMATION       ║"
                        echo "╚══════════════════════════════════════╝"
                        echo

                        echo -n "Enter URL or IP: "
                        read TARGET

                        if [ -z "$TARGET" ]; then
                            echo
                            echo "[!] No target entered."
                            sleep 2
                            continue
                        fi

                        # Add HTTPS if protocol was not entered
                        if [[ "$TARGET" != http://* && "$TARGET" != https://* ]]; then
                            TARGET="https://$TARGET"
                        fi

                        # Extract hostname
                        HOST=$(echo "$TARGET" | sed -E 's#https?://##' | cut -d/ -f1 | cut -d: -f1)

                        echo
                        echo "[+] Target : $TARGET"
                        echo "[+] Host   : $HOST"
                        echo

                        echo "----- DNS / IP -----"

                        IP=""

                        if command -v getent >/dev/null 2>&1; then
                            IP=$(getent ahostsv4 "$HOST" 2>/dev/null | awk 'NR==1 {print $1}')
                        fi

                        if [ -z "$IP" ] && command -v nslookup >/dev/null 2>&1; then
                            IP=$(nslookup "$HOST" 2>/dev/null | awk '/^Address: / {print $2}' | tail -n 1)
                        fi

                        if [ -n "$IP" ]; then
                            echo "IP        : $IP"
                        else
                            echo "IP        : Not resolved"
                        fi

                        echo
                        echo "----- HTTP / HTTPS -----"

                        if command -v curl >/dev/null 2>&1; then

                            HTTP_INFO=$(curl -k -L -s -o /dev/null \
                                -w "%{http_code}|%{url_effective}|%{http_version}|%{time_total}" \
                                --max-time 10 "$TARGET")

                            HTTP_CODE=$(echo "$HTTP_INFO" | cut -d'|' -f1)
                            FINAL_URL=$(echo "$HTTP_INFO" | cut -d'|' -f2)
                            HTTP_VERSION=$(echo "$HTTP_INFO" | cut -d'|' -f3)
                            RESPONSE_TIME=$(echo "$HTTP_INFO" | cut -d'|' -f4)

                            echo "Status    : $HTTP_CODE"
                            echo "Final URL : $FINAL_URL"
                            echo "HTTP      : $HTTP_VERSION"
                            echo "Response  : ${RESPONSE_TIME}s"

                        else
                            echo "[!] curl is not installed."
                        fi

                        echo
                        echo "----- TLS -----"

                        if [[ "$TARGET" == https://* ]]; then

                            if command -v openssl >/dev/null 2>&1; then

                                TLS_INFO=$(echo | openssl s_client \
                                    -connect "$HOST:443" \
                                    -servername "$HOST" \
                                    2>/dev/null)

                                if [ -n "$TLS_INFO" ]; then

                                    echo "$TLS_INFO" | openssl x509 \
                                        -noout \
                                        -subject \
                                        -issuer \
                                        -dates \
                                        2>/dev/null

                                else
                                    echo "TLS       : Unable to retrieve certificate."
                                fi

                            else
                                echo "[!] openssl is not installed."
                            fi

                        else
                            echo "TLS       : Target is HTTP."
                        fi

                        echo
                        echo "----- Security Headers -----"

                        if command -v curl >/dev/null 2>&1; then

                            HEADERS=$(curl -k -s -I -L \
                                --max-time 10 "$TARGET")

                            for HEADER in \
                                "strict-transport-security" \
                                "content-security-policy" \
                                "x-frame-options" \
                                "x-content-type-options" \
                                "referrer-policy" \
                                "permissions-policy"
                            do

                                RESULT=$(echo "$HEADERS" | grep -i "^$HEADER:" | tail -n 1)

                                if [ -n "$RESULT" ]; then
                                    echo "[+] $RESULT"
                                else
                                    echo "[-] $HEADER : Not found"
                                fi

                            done

                        fi

                        echo
                        echo "======================================"
                        read -p "Press Enter to continue..."

                        ;;


                    # ======================================
                    # DNS INFORMATION
                    # ======================================

                    2)

                        clear

                        echo "╔══════════════════════════════════════╗"
                        echo "║          X1 DNS INFORMATION         ║"
                        echo "╚══════════════════════════════════════╝"
                        echo

                        echo -n "Enter domain or URL: "
                        read TARGET

                        if [ -z "$TARGET" ]; then
                            echo "[!] No target entered."
                            sleep 2
                            continue
                        fi

                        HOST=$(echo "$TARGET" | sed -E 's#https?://##' | cut -d/ -f1 | cut -d: -f1)

                        echo
                        echo "[+] Domain: $HOST"
                        echo

                        if command -v nslookup >/dev/null 2>&1; then

                            nslookup "$HOST"

                        elif command -v dig >/dev/null 2>&1; then

                            dig "$HOST"

                        else

                            echo "[!] DNS tool is not installed."
                            echo
                            echo "Install it with:"
                            echo "pkg install dnsutils"

                        fi

                        echo
                        read -p "Press Enter to continue..."

                        ;;


                    # ======================================
                    # HTTP HEADERS
                    # ======================================

                    3)

                        clear

                        echo "╔══════════════════════════════════════╗"
                        echo "║            X1 HTTP HEADERS          ║"
                        echo "╚══════════════════════════════════════╝"
                        echo

                        echo -n "Enter URL or IP: "
                        read TARGET

                        if [ -z "$TARGET" ]; then
                            echo "[!] No target entered."
                            sleep 2
                            continue
                        fi

                        if [[ "$TARGET" != http://* && "$TARGET" != https://* ]]; then
                            TARGET="https://$TARGET"
                        fi

                        echo
                        echo "[+] Requesting headers..."
                        echo

                        if command -v curl >/dev/null 2>&1; then

                            curl -k -I -L --max-time 10 "$TARGET"

                        else

                            echo "[!] curl is not installed."

                        fi

                        echo
                        read -p "Press Enter to continue..."

                        ;;


                    # ======================================
                    # TLS CERTIFICATE
                    # ======================================

                    4)

                        clear

                        echo "╔══════════════════════════════════════╗"
                        echo "║          X1 TLS CERTIFICATE         ║"
                        echo "╚══════════════════════════════════════╝"
                        echo

                        echo -n "Enter domain: "
                        read HOST

                        HOST=$(echo "$HOST" | sed -E 's#https?://##' | cut -d/ -f1 | cut -d: -f1)

                        if [ -z "$HOST" ]; then
                            echo "[!] No domain entered."
                            sleep 2
                            continue
                        fi

                        echo
                        echo "[+] Checking: $HOST:443"
                        echo

                        if command -v openssl >/dev/null 2>&1; then

                            echo | openssl s_client \
                                -connect "$HOST:443" \
                                -servername "$HOST" \
                                2>/dev/null | \
                                openssl x509 \
                                -noout \
                                -subject \
                                -issuer \
                                -dates \
                                -fingerprint

                        else

                            echo "[!] openssl is not installed."

                        fi

                        echo
                        read -p "Press Enter to continue..."

                        ;;


                    # ======================================
                    # SECURITY HEADERS
                    # ======================================

                    5)

                        clear

                        echo "╔══════════════════════════════════════╗"
                        echo "║         X1 SECURITY HEADERS         ║"
                        echo "╚══════════════════════════════════════╝"
                        echo

                        echo -n "Enter URL: "
                        read TARGET

                        if [ -z "$TARGET" ]; then
                            echo "[!] No target entered."
                            sleep 2
                            continue
                        fi

                        if [[ "$TARGET" != http://* && "$TARGET" != https://* ]]; then
                            TARGET="https://$TARGET"
                        fi

                        echo
                        echo "[+] Checking security headers..."
                        echo

                        if command -v curl >/dev/null 2>&1; then

                            HEADERS=$(curl -k -s -I -L \
                                --max-time 10 "$TARGET")

                            echo "HSTS:"
                            echo "$HEADERS" | grep -i "^strict-transport-security:" || echo "Not found"

                            echo
                            echo "Content-Security-Policy:"
                            echo "$HEADERS" | grep -i "^content-security-policy:" || echo "Not found"

                            echo
                            echo "X-Frame-Options:"
                            echo "$HEADERS" | grep -i "^x-frame-options:" || echo "Not found"

                            echo
                            echo "X-Content-Type-Options:"
                            echo "$HEADERS" | grep -i "^x-content-type-options:" || echo "Not found"

                            echo
                            echo "Referrer-Policy:"
                            echo "$HEADERS" | grep -i "^referrer-policy:" || echo "Not found"

                            echo
                            echo "Permissions-Policy:"
                            echo "$HEADERS" | grep -i "^permissions-policy:" || echo "Not found"

                        else

                            echo "[!] curl is not installed."

                        fi

                        echo
                        read -p "Press Enter to continue..."

                        ;;


                    # ======================================
                    # BACK
                    # ======================================

                    0)

                        break

                        ;;


                    # ======================================
                    # INVALID START OPTION
                    # ======================================

                    *)

                        echo
                        echo "[!] Invalid choice."
                        sleep 1

                        ;;

                esac

            done

            ;;


        # ==================================================
        # ABOUT
        # ==================================================

        2)

            clear

            echo "╔════════════════════════════════╗"
            echo "║            ABOUT X1            ║"
            echo "╠════════════════════════════════╣"
            echo "║ Name    : X1                   ║"
            echo "║ Creator : X1                   ║"
            echo "║ Version : 1.0                  ║"
            echo "║ Telegram: @E365_X1             ║"
            echo "╠════════════════════════════════╣"
            echo "║ X1 یک اسکریپت برای Termux      ║"
            echo "║ است که ابزارهای مختلف Linux    ║"
            echo "║ و شبکه را در یک محیط ساده      ║"
            echo "║ و منظم جمع می‌کند.             ║"
            echo "╠════════════════════════════════╣"
            echo "║ Created by X1                  ║"
            echo "║ Telegram: @E365_X1             ║"
            echo "╚════════════════════════════════╝"

            echo
            read -p "Press Enter to continue..."

            ;;


        # ==================================================
        # EXIT
        # ==================================================

        0)

            clear

            echo "╔════════════════════════════════╗"
            echo "║           X1 EXIT              ║"
            echo "╠════════════════════════════════╣"
            echo "║ Thank you for using X1.        ║"
            echo "║                                ║"
            echo "║ X1 is shutting down...         ║"
            echo "║                                ║"
            echo "║ Created by X1                  ║"
            echo "║ Telegram: @E365_X1             ║"
            echo "╚════════════════════════════════╝"

            sleep 1
            clear
            exit 0

            ;;


        # ==================================================
        # INVALID MAIN OPTION
        # ==================================================

        *)

            echo
            echo "[!] Invalid choice."
            echo "Please select one of the numbers above."
            echo
            sleep 1

            ;;

    esac

    echo
    read -p "Press Enter to continue..."
    clear

done
